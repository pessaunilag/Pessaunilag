// Bundles the public-site renderer (src/site/legacy/*) into:
//   public/site.js + public/site.css   (served to browsers)
//   src/site/bundle.generated.ts       (same code, used for server-side rendering)
// Runs automatically before `pnpm dev` and `pnpm build`.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { createHash } from 'node:crypto'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const L = (f) => readFileSync(path.join(root, 'src/site/legacy', f), 'utf8')

const js = [L('a.js'), L('b.js'), L('d.js'), L('shell.js')].join('\n')
const css = L('style.css')
const hash = createHash('sha1').update(js + css).digest('hex').slice(0, 10)

// Syntax check before writing anything
new Function(js) // eslint-disable-line no-new-func

mkdirSync(path.join(root, 'public'), { recursive: true })
writeFileSync(path.join(root, 'public/site.js'), js)
writeFileSync(path.join(root, 'public/site.css'), css)
const safe = (s) => JSON.stringify(s).replace(/<\/script/gi, '<\\/script').replace(new RegExp("[\u2028\u2029]","g"), (c) => '\\u' + c.charCodeAt(0).toString(16))
writeFileSync(
  path.join(root, 'src/site/bundle.generated.ts'),
  `/* Generated by scripts/build-site.mjs. Do not edit. */\nexport const SITE_JS: string = ${safe(js)}\nexport const SITE_CSS: string = ${safe(css)}\nexport const SITE_HASH = ${JSON.stringify(hash)}\n`,
)
console.log(`site bundle ${hash}: ${(js.length / 1024).toFixed(0)} KB js, ${(css.length / 1024).toFixed(0)} KB css`)
